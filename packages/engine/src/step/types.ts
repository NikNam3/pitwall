// Protocol-free (C6): recorders and the bridge import these types; `StateUpdate` (`state-update/types.ts`) holds the
// frame.
import type { CarId, FrameNumber, MachineId, Ms, RaceEvent, SessionTime, Span } from '@pitwall/domain';
import type { LogWriter } from '../log/types.ts';
import { SPAN_TAGS } from '../situations/span-tags.generated.ts';
import type { Situation } from '../situations/situation.ts';
import type { LiveState } from '../state/live-state.ts';
import type { DeepReadonly } from '../util/deep-readonly.ts';

/**
 * Every part of the state a frame can change; calculators and the scheduler read these (C40): the live-state areas,
 * the history lists and one `spans:<id>` per sub-machine (the clock's here, the registered ones' generated by `pnpm gen`).
 */
export const CHANGE_TAGS = [
  'session',
  'identity',
  'timing',
  'tyres',
  'energy',
  'condition',
  'dynamics',
  'ownCar',
  'laps',
  'stints',
  'pitStops',
  'flagPhases',
  'events',
  'miniSectors',
  /** Step 0 appended a clock fact (`clock`: a fall, a jump, the simulated end). */
  'clock',
  /** The clock's open spans changed (a pause opened, its wall time so far grew) or a paused span closed. */
  'spans:clock',
  ...SPAN_TAGS,
] as const;
export type ChangeTag = (typeof CHANGE_TAGS)[number];
/** Every change tag, each once: what a flashback changes. */
export const ALL_CHANGE_TAGS: readonly ChangeTag[] = CHANGE_TAGS;

/** A provisional lap value that the game's Session History replaced with the confirmed one. */
export type LapCorrection = {
  carId: CarId;
  lapNumber: number;
  field: 'lapTimeMs' | 'sector1Ms' | 'sector2Ms';
  provisional: Ms;
  confirmed: Ms;
};

/**
 * The game's session time fell from `fromMs` to `toMs` with no flashback (a `fall` clock fact, C36): nothing recorded
 * changes, and the race clock continues over the fall.
 */
export type ClockFall = { fromMs: SessionTime; toMs: SessionTime };

/**
 * The game's session time jumped forward from `fromMs` to `toMs` by more than `SIMULATION_JUMP_MS` with no post-session
 * simulation (a stall while the clock runs ahead of wall time in the garage; a `jump` clock fact): nothing else changes
 * (spec 3.3).
 */
export type ClockJump = { fromMs: SessionTime; toMs: SessionTime };

/** What a rewind needs to know of the state it leaves: its frame id, the game's session time and its last wall time. */
export type RewindMark = { frameId: number; rawMs: SessionTime; lastWallMs: number | undefined };

/**
 * The `SessionRunner`'s decision that a frame reports a flashback, the one way it reaches the clock (step 0): no
 * session-time jump is read on the frame (spec 3.3). `rewound` when the runner rewound on it: the mark of the state it
 * left. The runner keeps the decision with the frame and gives it again whenever a later rewind replays the frame, so
 * the replay does what the first pass did.
 */
export type FlashbackReport = { rewound?: RewindMark };

/**
 * What a step did besides its tags: the provisional lap values Session History corrected, and a fall or a forward jump
 * of the session time step 0 read. No step changes or takes back what an earlier one recorded (C24): only a flashback
 * rewinds, and that is the runner's (C27).
 */
export type StepOutput = {
  changed: Set<ChangeTag>;
  corrections: LapCorrection[];
  clockFall?: ClockFall;
  clockJump?: ClockJump;
};

/** A step-3 module (C10): reads the live state, the situations and its own open state; appends facts to the log. */
export type Recorder<Own> = {
  id: string;
  init(): Own;
  apply(input: DeepReadonly<RecorderInput>, own: Own, log: LogWriter, out: StepOutput): Own;
};
/**
 * What a recorder reads of the frame (C10): its time on the race clock, its id and number, the live state and the
 * situations; never the frame or a signal (C6, C13). A fact records the frame it describes (C26), this frame's
 * `frameNumber` unless it describes an earlier one. `closed`: the spans step 2 closed on this frame, per sub-machine
 * (C9, C10), with how each closed (`confirmed`); a machine that closed none has no entry, and absent means none closed.
 * `tracked`: transitional, deleted
 * by Task 21 (`TrackedEvents`).
 */
export type RecorderInput = {
  at: SessionTime;
  frameId: number;
  frameNumber: FrameNumber;
  live: LiveState;
  situation: Situation;
  closed?: Readonly<Record<MachineId, readonly Span[]>>;
  tracked?: TrackedEvents;
};

/** A race event as recorded, before its time and the frame it describes. */
export type RaceEventBody = Omit<RaceEvent, 'at' | 'frame'>;

/**
 * Transitional (accepted ruling, Task 4): until the machine's spans carry them, step 2's slot hands the recorders what
 * this frame's situation events decided, so no recorder reads a signal (C13). `raceEvents`: the situation events still
 * recorded as race events, in arrival order (PENA, RTMT, DRSE, DRSD, STLG, LGOT); Task 21 deletes them, and with them
 * `RecorderInput.tracked`. Absent: none.
 */
export type TrackedEvents = { raceEvents: readonly RaceEventBody[] };
