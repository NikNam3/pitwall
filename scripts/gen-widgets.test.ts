import { mkdtempSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { describe, expect, it } from 'vitest';
import { findWidgetFolders, generateWidgets, renderWidgetsIndex } from './gen-widgets.ts';

const widget = (dir: string, name: string) => { mkdirSync(join(dir, name)); writeFileSync(join(dir, name, 'register.ts'), 'export default {};\n'); };

describe('gen-widgets', () => {
  it('collects folders with register.ts, sorted by code unit', () => {
    const dir = mkdtempSync(join(tmpdir(), 'widgets-'));
    widget(dir, 'undercut-card'); widget(dir, 'alpha'); widget(dir, 'Zeta');
    mkdirSync(join(dir, 'notes')); writeFileSync(join(dir, 'README.md'), '');
    expect(findWidgetFolders(dir)).toEqual(['Zeta', 'alpha', 'undercut-card']);
  });
  it('throws for a folder with .ts files but no register.ts, naming the folder', () => {
    const dir = mkdtempSync(join(tmpdir(), 'widgets-'));
    mkdirSync(join(dir, 'broken')); writeFileSync(join(dir, 'broken', 'widget.ts'), '');
    expect(() => findWidgetFolders(dir)).toThrow(/broken/);
  });
  it('throws when the widgets directory does not exist', () => {
    expect(() => findWidgetFolders(join(tmpdir(), 'no-such-widgets-dir-xyz'))).toThrow();
  });
  it('renders the exact index', () => {
    expect(renderWidgetsIndex(['gaps', 'undercut-card'])).toBe(
      "// Generated by scripts/gen-widgets.ts. Do not edit.\nimport type { RegisteredWidget } from '../kit/types.ts';\n" +
      "import widget0 from './gaps/register.ts';\nimport widget1 from './undercut-card/register.ts';\n\n" +
      'export const WIDGETS: RegisteredWidget[] = [widget0, widget1];\n');
    expect(renderWidgetsIndex([])).toContain('export const WIDGETS: RegisteredWidget[] = [];');
  });
  it('is deterministic and picks up a new widget folder', () => {
    const dir = mkdtempSync(join(tmpdir(), 'widgets-')); const out = join(dir, 'index.generated.ts');
    widget(dir, 'gaps');
    generateWidgets(dir, out); const first = readFileSync(out, 'utf8');
    generateWidgets(dir, out); expect(readFileSync(out, 'utf8')).toBe(first);
    widget(dir, 'temp-widget'); generateWidgets(dir, out);
    expect(readFileSync(out, 'utf8')).toBe(renderWidgetsIndex(['gaps', 'temp-widget']));
  });
});
