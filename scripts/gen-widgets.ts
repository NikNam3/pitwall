// Registration by convention: every folder under apps/ui/src/widgets with a register.ts is a widget.
import { existsSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const DEFAULT_WIDGETS_DIR = join(import.meta.dirname, '..', 'apps', 'ui', 'src', 'widgets');

const byCodeUnit = (a: string, b: string): number => (a < b ? -1 : a > b ? 1 : 0);

const isFile = (path: string): boolean => existsSync(path) && statSync(path).isFile();

/**
 * The names of the folders in `widgetsDir` that hold a `register.ts`, sorted by code unit.
 * A folder with TypeScript files but no `register.ts` is a mistake (a misspelt entry file would silently drop the
 * widget), so it throws; a folder without any, like `notes/`, is ignored.
 */
export function findWidgetFolders(widgetsDir: string): string[] {
  if (!existsSync(widgetsDir)) throw new Error(`widgets directory not found: ${widgetsDir}`);
  const folders: string[] = [];
  for (const name of readdirSync(widgetsDir)) {
    const folder = join(widgetsDir, name);
    if (!statSync(folder).isDirectory()) continue;
    if (isFile(join(folder, 'register.ts'))) {
      folders.push(name);
      continue;
    }
    const sources = readdirSync(folder).filter((entry) => /\.tsx?$/.test(entry));
    if (sources.length > 0) {
      throw new Error(`widget folder "${name}" has no register.ts file (found ${sources.join(', ')})`);
    }
  }
  return folders.sort(byCodeUnit);
}

/** The source of `index.generated.ts` for these widget folders: one import per `register.ts` and the `WIDGETS` list. */
export function renderWidgetsIndex(folders: readonly string[]): string {
  const imports = folders.map((folder, i) => `import widget${i} from './${folder}/register.ts';\n`);
  const list = folders.map((_, i) => `widget${i}`).join(', ');
  return (
    '// Generated by scripts/gen-widgets.ts. Do not edit.\n' +
    "import type { RegisteredWidget } from '../kit/types.ts';\n" +
    imports.join('') +
    `\nexport const WIDGETS: RegisteredWidget[] = [${list}];\n`
  );
}

/** Writes `outFile` (default: the index inside the widgets folder) from the widget folders found in `widgetsDir`. */
export function generateWidgets(
  widgetsDir: string = DEFAULT_WIDGETS_DIR,
  outFile: string = join(widgetsDir, 'index.generated.ts'),
): void {
  writeFileSync(outFile, renderWidgetsIndex(findWidgetFolders(widgetsDir)));
}

if (process.argv[1] === fileURLToPath(import.meta.url)) generateWidgets();
