// Shared by gen-features.ts and gen-widgets.ts: registration by convention, one folder with a register.ts per entry.
import { existsSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const byCodeUnit = (a: string, b: string): number => (a < b ? -1 : a > b ? 1 : 0);

const isFile = (path: string): boolean => existsSync(path) && statSync(path).isFile();

/**
 * The names of the folders in `dir` that hold a `register.ts`, sorted by code unit.
 * A folder with TypeScript files but no `register.ts` is a mistake (a misspelt entry file would silently drop the
 * entry), so it throws; a folder without any, like `notes/`, is ignored. `noun` ("feature", "widget") words the errors.
 */
export function findRegisterFolders(dir: string, noun: string): string[] {
  if (!existsSync(dir)) throw new Error(`${noun}s directory not found: ${dir}`);
  const folders: string[] = [];
  for (const name of readdirSync(dir)) {
    const folder = join(dir, name);
    if (!statSync(folder).isDirectory()) continue;
    if (isFile(join(folder, 'register.ts'))) {
      folders.push(name);
      continue;
    }
    const sources = readdirSync(folder).filter((entry) => /\.tsx?$/.test(entry));
    if (sources.length > 0) {
      throw new Error(`${noun} folder "${name}" has no register.ts file (found ${sources.join(', ')})`);
    }
  }
  return folders.sort(byCodeUnit);
}

/** The source of an `index.generated.ts`: one import per `register.ts` and the exported list. */
export function renderRegisterIndex(
  folders: readonly string[],
  o: { generator: string; typeImport: string; typeName: string; listName: string; importPrefix: string },
): string {
  const imports = folders.map((folder, i) => `import ${o.importPrefix}${i} from './${folder}/register.ts';\n`);
  const list = folders.map((_, i) => `${o.importPrefix}${i}`).join(', ');
  return (
    `// Generated by scripts/${o.generator}. Do not edit.\n` +
    `${o.typeImport}\n` +
    imports.join('') +
    `\nexport const ${o.listName}: ${o.typeName}[] = [${list}];\n`
  );
}

/** Writes `outFile` with `source`. */
export function writeIndex(outFile: string, source: string): void {
  writeFileSync(outFile, source);
}
