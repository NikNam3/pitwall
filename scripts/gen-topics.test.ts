import { mkdtempSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { describe, expect, it } from 'vitest';
import { findTopicFiles, generateTopics, renderTopicsIndex } from './gen-topics.ts';

const tempDir = () => mkdtempSync(join(tmpdir(), 'topics-'));
const topic = (dir: string, file: string) => writeFileSync(join(dir, file), 'export default {};\n');

describe('gen-topics', () => {
  it('collects the topic names of the .ts files, sorted by code unit', () => {
    const dir = tempDir();
    for (const file of ['session.info.ts', 'car.telemetry.ts', 'cars.overview.ts', 'car.detail.ts', 'laps.ts', 'pitStops.ts']) topic(dir, file);
    expect(findTopicFiles(dir)).toEqual(['car.detail', 'car.telemetry', 'cars.overview', 'laps', 'pitStops', 'session.info']);
  });
  it('sorts by code unit, not by locale', () => {
    const dir = tempDir();
    for (const file of ['ab.ts', 'cars.ts', 'aB.ts', 'car.x.ts']) topic(dir, file);
    expect(findTopicFiles(dir)).toEqual(['aB', 'ab', 'car.x', 'cars']);
  });
  it('ignores index.generated.ts, other file types and folders', () => {
    const dir = tempDir();
    topic(dir, 'laps.ts'); topic(dir, 'index.generated.ts');
    writeFileSync(join(dir, 'README.md'), ''); writeFileSync(join(dir, 'notes.txt'), '');
    mkdirSync(join(dir, 'sub.ts'));
    expect(findTopicFiles(dir)).toEqual(['laps']);
  });
  it('returns no names for an empty directory', () => {
    expect(findTopicFiles(tempDir())).toEqual([]);
  });
  it.each(['Laps.ts', '1laps.ts', 'car-detail.ts', 'car_detail.ts', 'car..detail.ts', '.laps.ts', 'laps..ts', 'car.Detail.ts', 'my topic.ts'])(
    'throws for the invalid topic name in %s',
    (file) => {
      const dir = tempDir();
      topic(dir, 'laps.ts'); topic(dir, file);
      expect(() => findTopicFiles(dir)).toThrow(/not a valid topic name/);
    },
  );
  it('names the offending file in the error', () => {
    const dir = tempDir();
    topic(dir, 'Bad-Name.ts');
    expect(() => findTopicFiles(dir)).toThrow(/Bad-Name\.ts/);
  });
  it('accepts dotted camelCase names', () => {
    const dir = tempDir();
    for (const file of ['a.ts', 'a1.b2C.ts', 'pitStops.ts']) topic(dir, file);
    expect(findTopicFiles(dir)).toEqual(['a', 'a1.b2C', 'pitStops']);
  });
  it('names the missing topics directory', () => {
    const dir = join(tempDir(), 'nope');
    expect(() => findTopicFiles(dir)).toThrow(`topics directory not found: ${dir}`);
  });
  it('renders the exact index', () => {
    expect(renderTopicsIndex(['car.detail', 'laps'])).toBe(
      '// Generated by scripts/gen-topics.ts. Do not edit.\n' +
      "import topic0 from './car.detail.ts';\n" +
      "import topic1 from './laps.ts';\n" +
      '\n' +
      'export const TOPICS = {\n' +
      "  'car.detail': { name: 'car.detail', ...topic0 },\n" +
      "  'laps': { name: 'laps', ...topic1 },\n" +
      '} as const;\n',
    );
  });
  it('renders an index without topics', () => {
    expect(renderTopicsIndex([])).toBe(
      '// Generated by scripts/gen-topics.ts. Do not edit.\n\nexport const TOPICS = {\n} as const;\n',
    );
  });
  it('writes the index, deterministically, and picks up a new topic file', () => {
    const dir = tempDir(); const out = join(dir, 'index.generated.ts');
    topic(dir, 'laps.ts');
    generateTopics(dir, out); const first = readFileSync(out, 'utf8');
    generateTopics(dir, out); expect(readFileSync(out, 'utf8')).toBe(first);
    expect(first).toBe(renderTopicsIndex(['laps']));
    topic(dir, 'car.detail.ts'); generateTopics(dir, out);
    expect(readFileSync(out, 'utf8')).toBe(renderTopicsIndex(['car.detail', 'laps']));
  });
  it('does not list its own previous output as a topic', () => {
    const dir = tempDir(); const out = join(dir, 'index.generated.ts');
    topic(dir, 'laps.ts');
    generateTopics(dir, out); generateTopics(dir, out);
    expect(readFileSync(out, 'utf8')).toBe(renderTopicsIndex(['laps']));
  });
});
