// Registration by convention (C15, C40, C63): every folder under packages/engine/src/situations with a machine.ts is a
// sub-machine. The generator writes the registry (`MACHINES`) and the sub-machines' change tags (`spans:<id>`, one per
// folder, as literals so `ChangeTag` names them); run as a script, it also fails on a cycle or an unknown upstream. It
// also writes domain's index of span declarations (`SPAN_DECLARATIONS`): every file `packages/domain/src/situations/<id>.ts`
// declares one sub-machine's (or the clock's) scope and span kinds as its export `spans`.
import { existsSync, readdirSync, statSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { writeIndex } from './gen-registry.ts';

const DEFAULT_SITUATIONS_DIR = join(import.meta.dirname, '..', 'packages', 'engine', 'src', 'situations');
const DEFAULT_DECLARATIONS_DIR = join(import.meta.dirname, '..', 'packages', 'domain', 'src', 'situations');
/** A generated file: never a declaration, the domain index included. */
const GENERATED = '.generated.ts';
/** The change tags' file, next to the index. */
const SPAN_TAGS_FILE = 'span-tags.generated.ts';

const byCodeUnit = (a: string, b: string): number => (a < b ? -1 : a > b ? 1 : 0);

/** The names of the folders in `situationsDir` that hold a `machine.ts`, sorted by code unit; every other entry is ignored. */
export function findMachineFolders(situationsDir: string): string[] {
  if (!existsSync(situationsDir)) throw new Error(`situations directory not found: ${situationsDir}`);
  return readdirSync(situationsDir)
    .filter((name) => {
      const machine = join(situationsDir, name, 'machine.ts');
      return statSync(join(situationsDir, name)).isDirectory() && existsSync(machine) && statSync(machine).isFile();
    })
    .sort(byCodeUnit);
}

/** The source of `index.generated.ts` for these folders: one import per `machine.ts` default export and the `MACHINES` list. */
export function renderMachinesIndex(folders: readonly string[]): string {
  const imports = folders.map((folder, i) => `import machine${i} from './${folder}/machine.ts';\n`);
  const list = folders.map((_, i) => `machine${i}`).join(', ');
  return (
    '// Generated by scripts/gen-machines.ts. Do not edit.\n' +
    "import type { SubMachine } from './machine.ts';\n" +
    imports.join('') +
    `\nexport const MACHINES: SubMachine<unknown>[] = [${list}];\n`
  );
}

/** The source of `span-tags.generated.ts`: the change tag `spans:<id>` of every sub-machine folder (C40). */
export function renderSpanTags(folders: readonly string[]): string {
  const tags = folders.map((folder) => `'spans:${folder}'`).join(', ');
  return (
    '// Generated by scripts/gen-machines.ts. Do not edit.\n' +
    '/** The change tag of every sub-machine (C40): `spans:<id>`, one per folder `situations/<id>/`. */\n' +
    `export const SPAN_TAGS = [${tags}] as const;\n`
  );
}

/** Writes `outFile` (default: the index inside the situations folder) and the change tags next to it. */
export function generateMachines(
  situationsDir: string = DEFAULT_SITUATIONS_DIR,
  outFile: string = join(situationsDir, 'index.generated.ts'),
): void {
  const folders = findMachineFolders(situationsDir);
  writeIndex(outFile, renderMachinesIndex(folders));
  writeIndex(join(dirname(outFile), SPAN_TAGS_FILE), renderSpanTags(folders));
}

/**
 * The span declaration files in `declarationsDir`, as names without `.ts` sorted by code unit: every `.ts` file that is
 * not generated (`*.generated.ts`); folders and other files are ignored.
 */
export function findSpanDeclarationFiles(declarationsDir: string): string[] {
  if (!existsSync(declarationsDir)) throw new Error(`span declarations directory not found: ${declarationsDir}`);
  return readdirSync(declarationsDir)
    .filter((name) => name.endsWith('.ts') && !name.endsWith(GENERATED) && statSync(join(declarationsDir, name)).isFile())
    .map((name) => name.slice(0, -'.ts'.length))
    .sort(byCodeUnit);
}

/** The source of domain's `situations/index.generated.ts`: one import per file's `spans` and the `SPAN_DECLARATIONS` list. */
export function renderSpanDeclarationsIndex(names: readonly string[]): string {
  const imports = names.map((name, i) => `import { spans as spans${i} } from './${name}.ts';\n`);
  const list = names.map((_, i) => `spans${i}`).join(', ');
  return (
    '// Generated by scripts/gen-machines.ts. Do not edit.\n' +
    "import type { SpanDeclaration } from '../facts.ts';\n" +
    imports.join('') +
    `\nexport const SPAN_DECLARATIONS: readonly SpanDeclaration[] = [${list}];\n`
  );
}

/** Writes `outFile` (default: the index inside the declarations folder), listing every declaration file of `declarationsDir`. */
export function generateSpanDeclarations(
  declarationsDir: string = DEFAULT_DECLARATIONS_DIR,
  outFile: string = join(declarationsDir, 'index.generated.ts'),
): void {
  writeIndex(outFile, renderSpanDeclarationsIndex(findSpanDeclarationFiles(declarationsDir)));
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  // Domain's index first: the registry's sub-machines read their declarations through it.
  generateSpanDeclarations();
  generateMachines();
  // A cycle or an upstream that is not registered fails generation (C15): the registry orders the written index on load.
  await import(pathToFileURL(join(DEFAULT_SITUATIONS_DIR, 'registry.ts')).href);
}
