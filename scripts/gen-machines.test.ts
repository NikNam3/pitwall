import { mkdtempSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { describe, expect, it } from 'vitest';
import {
  findMachineFolders,
  findSpanDeclarationFiles,
  generateMachines,
  generateSpanDeclarations,
  renderMachinesIndex,
  renderSpanDeclarationsIndex,
} from './gen-machines.ts';

// The domain index (C15, C63): every `.ts` file of `packages/domain/src/situations/` that is not generated
// (`*.generated.ts`, the index itself) is one sub-machine's (or the clock's) span declaration, its named export `spans`;
// the index lists them as `SPAN_DECLARATIONS`, sorted by file name (code unit), which is the machine id.
const declaration = (dir: string, name: string) => writeFileSync(join(dir, `${name}.ts`), `export const spans = { machine: '${name}' };\n`);

const machine = (dir: string, name: string) => { mkdirSync(join(dir, name)); writeFileSync(join(dir, name, 'machine.ts'), 'export default {};\n'); };

describe('gen-machines', () => {
  it('collects the folders with a machine.ts, sorted by code unit, and ignores the rest', () => {
    const dir = mkdtempSync(join(tmpdir(), 'situations-'));
    machine(dir, 'car-location'); machine(dir, 'Zeta'); machine(dir, 'car-activity-race');
    mkdirSync(join(dir, 'helpers')); writeFileSync(join(dir, 'helpers', 'shared.ts'), '');
    writeFileSync(join(dir, 'machine.ts'), ''); writeFileSync(join(dir, 'situation.ts'), '');
    expect(findMachineFolders(dir)).toEqual(['Zeta', 'car-activity-race', 'car-location']);
  });
  it('throws when the situations directory does not exist', () => {
    expect(() => findMachineFolders(join(tmpdir(), 'no-such-situations-dir-xyz'))).toThrow();
  });
  it('renders the exact index: every machine.ts default export in MACHINES', () => {
    expect(renderMachinesIndex(['car-location', 'session-phase-race'])).toBe(
      "// Generated by scripts/gen-machines.ts. Do not edit.\nimport type { SubMachine } from './machine.ts';\n" +
      "import machine0 from './car-location/machine.ts';\nimport machine1 from './session-phase-race/machine.ts';\n\n" +
      'export const MACHINES: SubMachine<unknown>[] = [machine0, machine1];\n');
    expect(renderMachinesIndex([])).toContain('export const MACHINES: SubMachine<unknown>[] = [];');
  });
  it('is deterministic and picks up a new machine folder', () => {
    const dir = mkdtempSync(join(tmpdir(), 'situations-')); const out = join(dir, 'index.generated.ts');
    machine(dir, 'car-location');
    generateMachines(dir, out); const first = readFileSync(out, 'utf8');
    generateMachines(dir, out); expect(readFileSync(out, 'utf8')).toBe(first);
    machine(dir, 'car-status'); generateMachines(dir, out);
    expect(readFileSync(out, 'utf8')).toBe(renderMachinesIndex(['car-location', 'car-status']));
  });

  it('the domain index lists every declaration file of the folder, sorted', () => {
    const dir = mkdtempSync(join(tmpdir(), 'domain-situations-'));
    declaration(dir, 'clock'); declaration(dir, 'Zeta'); declaration(dir, 'car-location');
    // neither a generated file, a file that is no .ts module, nor a folder is a declaration
    writeFileSync(join(dir, 'index.generated.ts'), ''); writeFileSync(join(dir, 'other.generated.ts'), ''); writeFileSync(join(dir, 'notes.md'), '');
    mkdirSync(join(dir, 'helpers')); writeFileSync(join(dir, 'helpers', 'shared.ts'), '');
    expect(findSpanDeclarationFiles(dir)).toEqual(['Zeta', 'car-location', 'clock']);
    generateSpanDeclarations(dir);
    expect(readFileSync(join(dir, 'index.generated.ts'), 'utf8')).toBe(renderSpanDeclarationsIndex(['Zeta', 'car-location', 'clock']));
  });
  it('renders the exact domain index: every file\'s spans in SPAN_DECLARATIONS', () => {
    expect(renderSpanDeclarationsIndex(['car-location', 'clock'])).toBe(
      "// Generated by scripts/gen-machines.ts. Do not edit.\nimport type { SpanDeclaration } from '../facts.ts';\n" +
      "import { spans as spans0 } from './car-location.ts';\nimport { spans as spans1 } from './clock.ts';\n\n" +
      'export const SPAN_DECLARATIONS: readonly SpanDeclaration[] = [spans0, spans1];\n');
    expect(renderSpanDeclarationsIndex([])).toContain('export const SPAN_DECLARATIONS: readonly SpanDeclaration[] = [];');
  });
  it('the domain index is deterministic, picks up a new declaration file and is written where asked', () => {
    const dir = mkdtempSync(join(tmpdir(), 'domain-situations-')); const out = join(dir, 'out.generated.ts');
    declaration(dir, 'clock');
    generateSpanDeclarations(dir, out); const first = readFileSync(out, 'utf8');
    generateSpanDeclarations(dir, out); expect(readFileSync(out, 'utf8')).toBe(first);
    declaration(dir, 'car-status'); generateSpanDeclarations(dir, out);
    // the index written there is generated, so no declaration of its folder
    expect(readFileSync(out, 'utf8')).toBe(renderSpanDeclarationsIndex(['car-status', 'clock']));
  });
  it('throws when the domain situations directory does not exist', () => {
    expect(() => findSpanDeclarationFiles(join(tmpdir(), 'no-such-domain-situations-dir-xyz'))).toThrow();
  });
});
