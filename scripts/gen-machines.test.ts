import { mkdtempSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { describe, expect, it } from 'vitest';
import { findMachineFolders, generateMachines, renderMachinesIndex } from './gen-machines.ts';

const machine = (dir: string, name: string) => { mkdirSync(join(dir, name)); writeFileSync(join(dir, name, 'machine.ts'), 'export default {};\n'); };

describe('gen-machines', () => {
  it('collects the folders with a machine.ts, sorted by code unit, and ignores the rest', () => {
    const dir = mkdtempSync(join(tmpdir(), 'situations-'));
    machine(dir, 'car-location'); machine(dir, 'Zeta'); machine(dir, 'car-activity-race');
    mkdirSync(join(dir, 'helpers')); writeFileSync(join(dir, 'helpers', 'shared.ts'), '');
    writeFileSync(join(dir, 'machine.ts'), ''); writeFileSync(join(dir, 'situation.ts'), '');
    expect(findMachineFolders(dir)).toEqual(['Zeta', 'car-activity-race', 'car-location']);
  });
  it('throws when the situations directory does not exist', () => {
    expect(() => findMachineFolders(join(tmpdir(), 'no-such-situations-dir-xyz'))).toThrow();
  });
  it('renders the exact index: every machine.ts default export in MACHINES', () => {
    expect(renderMachinesIndex(['car-location', 'session-phase-race'])).toBe(
      "// Generated by scripts/gen-machines.ts. Do not edit.\nimport type { SubMachine } from './machine.ts';\n" +
      "import machine0 from './car-location/machine.ts';\nimport machine1 from './session-phase-race/machine.ts';\n\n" +
      'export const MACHINES: SubMachine<unknown>[] = [machine0, machine1];\n');
    expect(renderMachinesIndex([])).toContain('export const MACHINES: SubMachine<unknown>[] = [];');
  });
  it('is deterministic and picks up a new machine folder', () => {
    const dir = mkdtempSync(join(tmpdir(), 'situations-')); const out = join(dir, 'index.generated.ts');
    machine(dir, 'car-location');
    generateMachines(dir, out); const first = readFileSync(out, 'utf8');
    generateMachines(dir, out); expect(readFileSync(out, 'utf8')).toBe(first);
    machine(dir, 'car-status'); generateMachines(dir, out);
    expect(readFileSync(out, 'utf8')).toBe(renderMachinesIndex(['car-location', 'car-status']));
  });
});
