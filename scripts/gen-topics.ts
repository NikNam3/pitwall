// Registration by convention: every `<topic name>.ts` file in packages/contracts/src/topics is a topic.
import { existsSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const DEFAULT_TOPICS_DIR = join(import.meta.dirname, '..', 'packages', 'contracts', 'src', 'topics');
const INDEX_FILE = 'index.generated.ts';
const TOPIC_NAME = /^[a-z][A-Za-z0-9]*(\.[a-z][A-Za-z0-9]*)*$/;

const byCodeUnit = (a: string, b: string): number => (a < b ? -1 : a > b ? 1 : 0);

/**
 * The topic names (file names without `.ts`) in `topicsDir`, sorted by code unit.
 * A file whose name is not a valid topic name is a mistake, so it throws.
 */
export function findTopicFiles(topicsDir: string): string[] {
  if (!existsSync(topicsDir)) throw new Error(`topics directory not found: ${topicsDir}`);
  const names: string[] = [];
  for (const file of readdirSync(topicsDir)) {
    if (!file.endsWith('.ts') || file === INDEX_FILE) continue;
    if (!statSync(join(topicsDir, file)).isFile()) continue;
    const name = file.slice(0, -'.ts'.length);
    if (!TOPIC_NAME.test(name)) throw new Error(`"${file}" is not a valid topic name (expected ${TOPIC_NAME})`);
    names.push(name);
  }
  return names.sort(byCodeUnit);
}

export function renderTopicsIndex(names: readonly string[]): string {
  const imports = names.map((name, i) => `import topic${i} from './${name}.ts';\n`);
  const entries = names.map((name, i) => `  '${name}': { name: '${name}', ...topic${i} },\n`);
  return (
    '// Generated by scripts/gen-topics.ts. Do not edit.\n' +
    imports.join('') +
    '\nexport const TOPICS = {\n' +
    entries.join('') +
    '} as const;\n'
  );
}

export function generateTopics(
  topicsDir: string = DEFAULT_TOPICS_DIR,
  outFile: string = join(topicsDir, INDEX_FILE),
): void {
  writeFileSync(outFile, renderTopicsIndex(findTopicFiles(topicsDir)));
}

if (process.argv[1] === fileURLToPath(import.meta.url)) generateTopics();
